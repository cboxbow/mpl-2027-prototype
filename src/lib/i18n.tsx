const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: string) => string }>({ lang: "en", setLang: () => {}, t: (k) => k });
export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(CURRENT_LANG);
  const set = (l: Lang) => { setLang(l); try { localStorage.setItem("mpl27-lang", l); } catch { /* ignore */ } if (l !== CURRENT_LANG) window.location.reload(); };
  const t = (k: string) => dict[k]?.[lang] ?? dict[k]?.en ?? k;
  return <Ctx.Provider value={{ lang, setLang: set, t }}>{children}</Ctx.Provider>;
}
export const useI18n = () => useContext(Ctx);
